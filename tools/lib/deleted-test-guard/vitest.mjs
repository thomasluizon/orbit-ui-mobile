/** Vitest runs of the guard: the generated config, the project lookup, the related tests and a coverage run. */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join, relative } from "node:path"

/** A path from the repository root, as a path from the workspace folder. */
const inWorkspace = (workspace, file) => relative(workspace, file)
import { fileURLToPath } from "node:url"
import { runBounded } from "../bounded-process.mjs"

const HELPER = join(dirname(fileURLToPath(import.meta.url)), "vitest-helper.mjs")
const RESULT = /@@RESULT@@(.*)$/m

/** The name of the generated config of a workspace, next to its own config. */
export const GENERATED_CONFIG = ".stryker-guard.vitest.config.ts"

/**
 * The text of the generated config. It reads the workspace config and copies it. The one project of the lost tests keeps its
 * own settings, and only its `include` changes. Vite `mergeConfig` is no choice: it joins arrays.
 */
export const generatedConfigText = ({ project, include, root, coverageDirectory }) => `// Generated by tools/deleted-test-guard.mjs. Never commit it.
import original from './vitest.config'

const test = original.test ?? {}
const entry = (test.projects ?? []).find((candidate) => candidate?.test?.name === ${JSON.stringify(project)})
if (entry === undefined) throw new Error('The workspace config has no project named ${project}')

export default {
  ...original,
  root: ${JSON.stringify(root)},
  test: {
    ...test,
    projects: [{ ...entry, test: { ...entry.test, include: ${JSON.stringify(include)} } }],
    coverage: {
      ...test.coverage,
      // An absolute pattern: Vitest matches no file with the relative pattern ../../packages/shared/src/**.
      include: [...(test.coverage?.include ?? []), ${JSON.stringify(join(root, "../../packages/shared/src/**"))}],
      allowExternal: true,
      reporter: ['lcovonly'],
      reportsDirectory: ${JSON.stringify(coverageDirectory)},
      thresholds: {},
    },
  },
}
`

/** Writes the generated config into a workspace of a checkout and returns its path. */
export const writeGeneratedConfig = ({ checkout, workspace, project, include, coverageDirectory }) => {
  const path = join(checkout, workspace, GENERATED_CONFIG)
  writeFileSync(path, generatedConfigText({ project, include, root: join(checkout, workspace), coverageDirectory }))
  return path
}

const helper = async ({ checkout, workspace, args, timeoutMs }) => {
  const result = await runBounded(process.execPath, [HELPER, ...args], { cwd: join(checkout, workspace), env: process.env, timeoutMs })
  const match = RESULT.exec(result.stdout)
  if (result.status !== 0 || match === null) throw new Error(`vitest helper ${args[0]} failed: ${(result.timedOut ? "timed out" : result.stderr || result.stdout).trim().slice(-600)}`)
  return JSON.parse(match[1])
}

/** The project of a test file in a checkout, as a string. */
export const projectOf = ({ checkout, workspace, file, timeoutMs }) =>
  helper({ checkout, workspace, args: ["project-of", inWorkspace(workspace, file)], timeoutMs })

/** The test files (paths from the repository root) that `vitest related` selects for source files, in one project. */
export const relatedTests = async ({ checkout, workspace, project, files, timeoutMs }) => {
  if (files.length === 0) return []
  const found = await helper({ checkout, workspace, args: ["related", project, ...files.map((file) => inWorkspace(workspace, file))], timeoutMs })
  return found.map((path) => relative(checkout, path)).sort()
}

/** One coverage run of test files in one project. Returns the text of `lcov.info` and the exit status of Vitest. */
export const runCoverage = async ({ checkout, workspace, project, tests, coverageDirectory, timeoutMs }) => {
  const config = writeGeneratedConfig({ checkout, workspace, project, include: tests.map((file) => inWorkspace(workspace, file)), coverageDirectory })
  mkdirSync(coverageDirectory, { recursive: true })
  const bin = join(checkout, "node_modules", "vitest", "vitest.mjs")
  const result = await runBounded(process.execPath, [bin, "run", "--config", config, "--coverage.enabled", "--reporter=dot"], {
    cwd: join(checkout, workspace), env: process.env, timeoutMs,
  })
  let lcov = ""
  try {
    lcov = readFileSync(join(coverageDirectory, "lcov.info"), "utf8")
  } catch {
    // A run that stopped early writes no report. The caller reads the empty text as no coverage.
  }
  return { lcov, status: result.timedOut ? "timeout" : result.status, output: `${result.stdout}${result.stderr}`.slice(-2000) }
}
