import { spawnSync } from 'node:child_process'
import { readFileSync, writeFileSync, mkdirSync, mkdtempSync, rmSync, readdirSync, symlinkSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { resolve } from 'node:path'
import { afterEach, describe, expect, it } from 'vitest'
import { contractOptions, generatedDirectory, readContract, resolveContract, validateCommit, readProducerFile } from './contract-source.mjs'
import { regenerate } from './generate-contract.mjs'

const producer = '84b8829f24fc258a744a3cc9d26f52407eb53f99'
const selection = { id: 'orbit-http-v1-r2', httpVersion: '1.0' }
const fixtureDirectory = new URL('./__fixtures__/', import.meta.url)
const fixture = (name) => readFileSync(new URL(name, fixtureDirectory), 'utf8')
const catalog = JSON.parse(fixture('artifacts.json'))
const read = (_commit, path) => fixture(path.split('/').at(-1))
const selected = { commit: producer, selection }
const roots = []

function stage(metadata = selection) {
  const root = mkdtempSync(resolve(tmpdir(), 'orbit-contract-'))
  roots.push(root)
  const directory = resolve(root, generatedDirectory)
  mkdirSync(directory, { recursive: true })
  writeFileSync(resolve(directory, 'api.spec.commit'), `${producer}\n`)
  writeFileSync(resolve(directory, 'api.generated.ts'), 'previous output\n')
  if (metadata !== undefined) writeFileSync(resolve(directory, 'api.spec.selection.json'), JSON.stringify(metadata))
  return { root, directory }
}

afterEach(() => {
  delete process.env.ORBIT_OPENAPI_SPEC
  for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true })
})

describe('immutable contract selection using the committed producer fixtures', () => {
  it('reads the complete accepted catalog and corrected HTTP v1 and v2 documents', () => {
    expect(resolveContract(selected, read)).toEqual(JSON.parse(fixture('openapi_v1-r2.json')))
    expect(resolveContract({ commit: producer, selection: { id: 'orbit-http-v2-r2', httpVersion: '2.0' } }, read))
      .toEqual(JSON.parse(fixture('openapi_v2-r2.json')))
    expect(contractOptions(resolveContract(selected, read)).output.override.zod.version).toBe(4)
    const document = resolveContract(selected, read)
    expect(contractOptions(document).output.override.header(document.info)).toEqual([
      'Generated by orval 🍺', 'Do not edit manually.', 'Orbit.Api | v1-r2', 'OpenAPI spec version: 1.0',
    ])
  })

  it('keeps absent metadata on legacy v1 without requiring a catalog', () => {
    const calls = []
    const document = resolveContract({ commit: producer }, (commit, path) => {
      calls.push([commit, path])
      return read(commit, path)
    })
    expect(calls).toEqual([[producer, 'src/Orbit.Api/openapi.json']])
    expect(document).toEqual(JSON.parse(fixture('openapi.json')))
    expect(contractOptions(document).output.override.header).toBeUndefined()
    const { root, directory } = stage()
    rmSync(resolve(directory, 'api.spec.selection.json'))
    expect(readContract(root)).toEqual({ commit: producer, selection: undefined })
  })

  it.each(['main', 'a'.repeat(39), 'a'.repeat(41), 'A'.repeat(40), `${producer}\n`, `${producer};echo bad`, `https://example.test/${producer}`])('rejects invalid commit %s before reading', (commit) => {
    let reads = 0
    expect(() => resolveContract({ ...selected, commit }, () => { reads += 1 })).toThrow('40-character SHA')
    expect(reads).toBe(0)
    expect(() => validateCommit(commit)).toThrow()
  })

  it.each([null, {}, { id: selection.id }, { ...selection, path: 'https://example.test' },
    { ...selection, id: '../openapi' }, { ...selection, id: 'orbit-http-v1-r02' },
    { ...selection, id: 'orbit-http-v3-r2' }, { ...selection, id: 'orbit-http-v1-r2\n' }, { ...selection, id: '$(echo bad)' },
    { ...selection, httpVersion: '2.0' }])('rejects malformed explicit selections before reading: %j', (metadata) => {
    let reads = 0
    expect(() => resolveContract({ commit: producer, selection: metadata }, () => { reads += 1 })).toThrow()
    expect(reads).toBe(0)
  })

  it('does not convert malformed on-disk metadata into absent legacy metadata', () => {
    const { root, directory } = stage()
    writeFileSync(resolve(directory, 'api.spec.selection.json'), '{')
    expect(() => readContract(root)).toThrow()
  })

  it('refuses a broken metadata symlink instead of selecting legacy', () => {
    const { root, directory } = stage()
    const path = resolve(directory, 'api.spec.selection.json')
    rmSync(path)
    symlinkSync(resolve(root, 'missing.json'), path)
    expect(() => readContract(root)).toThrow('regular file')
  })

  it.each([
    (rows) => rows.filter((row) => row.id !== selection.id),
    (rows) => { delete rows[2].path; return rows },
    (rows) => { rows[2].httpVersion = '2.0'; return rows },
    (rows) => { rows[2].revision = 'r3'; return rows },
    (rows) => { rows[2].documentName = 'v2-r2'; return rows },
    (rows) => { rows[2].path = '../openapi.json'; return rows },
    (rows) => { rows[2].path = 'https://example.test/openapi.json'; return rows },
    (rows) => { rows[2].path = 'src/Orbit.Api/$(echo bad).json'; return rows },
    (rows) => { rows[2].deprecated = 'false'; return rows },
    (rows) => { rows[0].replacement = 'orbit-http-v2-r2'; return rows },
    (rows) => [...rows, rows[2]],
    (rows) => rows.slice(1),
    () => [],
    () => ({}),
  ])('fails catalog mutations without fetching any document', (mutate) => {
    const paths = []
    expect(() => resolveContract(selected, (_commit, path) => {
      paths.push(path)
      return JSON.stringify(mutate(structuredClone(catalog)))
    })).toThrow()
    expect(paths).toEqual(['src/Orbit.Api/OpenApi/artifacts.json'])
  })

  it.each([
    (document) => { document.info.version = '2.0' },
    (document) => { document.info.title = 'Orbit.Api | v1' },
    (document) => { document.info.description = 'wrong revision' },
    (document) => { document.paths = {} },
    (document) => { document.openapi = 'invalid' },
    (document) => { document.components.schemas.FrequencyUnit = { $ref: 'https://example.test/schema' } },
  ])('rejects document identity, version and reference mutations', (mutate) => {
    const document = JSON.parse(fixture('openapi_v1-r2.json'))
    mutate(document)
    expect(() => resolveContract(selected, (commit, path) => path.endsWith('artifacts.json') ? read(commit, path) : JSON.stringify(document))).toThrow()
  })

  it.each(['catalog', 'document', 'parse'])('propagates %s failures without legacy fallback', (failure) => {
    const paths = []
    expect(() => resolveContract(selected, (commit, path) => {
      paths.push(path)
      if (failure === 'parse') return '{'
      if (failure === 'catalog' || !path.endsWith('artifacts.json')) throw new Error('404/auth/network failure')
      return read(commit, path)
    })).toThrow()
    expect(paths).not.toContain('src/Orbit.Api/openapi.json')
  })

  it('rejects arbitrary producer paths before invoking curl', () => {
    for (const path of ['../openapi.json', 'https://example.test', 'src/Other/openapi.json', 'src/Orbit.Api/openapi_v3-r2.json', 'src/Orbit.Api/openapi.json\n']) {
      expect(() => readProducerFile(producer, path)).toThrow('artifact path')
    }
  })

  it('accepts only an explicit local investigation document with the selected identity', () => {
    const local = new URL('./__fixtures__/openapi_v1-r2.json', import.meta.url).pathname
    expect(resolveContract(selected, read, local).info.version).toBe('1.0')
    for (const override of ['https://example.test/openapi.json', 'relative.json', 'file:///document', `${local}\n`]) {
      expect(() => resolveContract(selected, read, override)).toThrow('absolute local')
    }
    expect(() => resolveContract(selected, read, new URL('./__fixtures__/openapi_v2-r2.json', import.meta.url).pathname)).toThrow('identity mismatch')
  })
})

describe('transactional generation and stale-output guard', () => {
  const generator = async (options) => { writeFileSync(options.output.target, 'new output\n') }

  it('moves a SHA with identical generated bytes and preserves selection', async () => {
    const { root, directory } = stage()
    writeFileSync(resolve(directory, 'api.generated.ts'), 'new output\n')
    const candidate = 'a'.repeat(40)
    const requests = []
    await regenerate({ root, candidate, read: (commit, path) => { requests.push(commit); return read(commit, path) }, generator })
    expect(readContract(root)).toEqual({ commit: candidate, selection })
    expect(requests).toEqual([candidate, candidate])
    expect(readFileSync(resolve(directory, 'api.generated.ts'), 'utf8')).toBe('new output\n')
  })

  it('rejects stale bytes and accepts matching bytes without changing any source file', async () => {
    const { root, directory } = stage()
    await expect(regenerate({ root, check: true, read, generator })).rejects.toThrow('Stale contract snapshot')
    expect(readFileSync(resolve(directory, 'api.generated.ts'), 'utf8')).toBe('previous output\n')
    await regenerate({ root, read, generator })
    await expect(regenerate({ root, check: true, read, generator })).resolves.toBeUndefined()
    expect(readContract(root)).toEqual(selected)
  })

  it('preserves the previous complete set after interrupted generation', async () => {
    const { root, directory } = stage()
    await expect(regenerate({ root, candidate: 'a'.repeat(40), read, generator: async (options) => {
      writeFileSync(options.output.target, 'partial output')
      throw new Error('generation interrupted')
    } })).rejects.toThrow('interrupted')
    expect(readContract(root)).toEqual(selected)
    expect(readFileSync(resolve(directory, 'api.generated.ts'), 'utf8')).toBe('previous output\n')
    expect(readdirSync(directory).sort()).toEqual(['api.generated.ts', 'api.spec.commit', 'api.spec.selection.json'])
  })

  it('fails before generation on a missing document and refuses committed overrides', async () => {
    const { root } = stage()
    await expect(regenerate({ root, read: () => { throw new Error('unavailable') }, generator })).rejects.toThrow('unavailable')
    expect(readContract(root)).toEqual(selected)
    process.env.ORBIT_OPENAPI_SPEC = '/investigation.json'
    await expect(regenerate({ root, read, generator })).rejects.toThrow('Investigation overrides')
  })

  it('rejects bad CLI arguments without changing the committed set', () => {
    const result = spawnSync(process.execPath, [new URL('./generate-contract.mjs', import.meta.url).pathname, '--candidate', 'main'], { encoding: 'utf8' })
    expect(result.status).toBe(1)
    expect(result.stderr).toContain('40-character SHA')
  })
})
