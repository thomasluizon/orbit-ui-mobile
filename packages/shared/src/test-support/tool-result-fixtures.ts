export function makeEmojiToolResult(count: number): ActionResult {
  return actionResultSchema.parse({
    type: 'bulk_update_habit_emojis',
    status: 'Success',
    entityName: `Updated emojis for ${count} of ${count} matching habit(s). Skipped 0. Complete result.`,
    messageKey: 'chat.toolResult.updatedEmojis',
    params: { count, totalCount: count, skippedCount: 0, partial: false },
  })
}
