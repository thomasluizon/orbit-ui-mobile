import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url))
const mobileDirectory = path.resolve(scriptDirectory, '..')
type PaletteKey =
  | 'bg'
  | 'card'
  | 'well'
  | 'hairline'
  | 'fg1'
  | 'fg2'
  | 'fg3'
  | 'fg4'
  | 'trackEmpty'
  | 'primaryText'
  | 'overdue'
type PaletteEntry = readonly [value: string, token: string]
type Palette = Record<PaletteKey, PaletteEntry>

/** The granted canvas palette and its token provenance for generated outputs. */
const PALETTES = {
  dark: {
    bg: ['#09090B', '--bg'],
    card: ['#131315', '--bg-card flattened over --bg'],
    well: ['#1D1D1F', '--bg-well flattened over --bg'],
    hairline: ['#2B2B2D', '--hairline-ghost flattened over --bg-card'],
    fg1: ['#F4F4F6', '--fg-1'],
    fg2: ['#C9C9CC', '--fg-2'],
    fg3: ['#8F8F93', '--fg-3'],
    fg4: ['#5D5D60', '--fg-4'],
    trackEmpty: ['#8B8B8E', '--track-empty'],
    primaryText: ['#ED773E', '--primary-text'],
    overdue: ['#FE9A00', '--status-overdue'],
  },
  light: {
    bg: ['#FAFAFA', '--bg'],
    card: ['#FFFFFF', '--bg-card'],
    well: ['#F1F1F2', '--bg-well flattened over --bg'],
    hairline: ['#E6E6E8', '--hairline flattened over --bg-card'],
    fg1: ['#1A1A1D', '--fg-1'],
    fg2: ['#424247', '--fg-2'],
    fg3: ['#68686D', '--fg-3'],
    fg4: ['#89898D', '--fg-4'],
    trackEmpty: ['#7E7E82', '--track-empty'],
    primaryText: ['#A63A00', '--primary-text'],
    overdue: ['#7D5700', '--status-overdue'],
  },
} as const satisfies Record<'dark' | 'light', Palette>

function generatedTypeScript() {
  const modes = Object.entries(PALETTES).map(([mode, palette]) => {
    const colors = (Object.entries(palette) as [PaletteKey, PaletteEntry][])
      .map(([name, [value, token]]) => `    /** WHY: ${token}. */\n    ${name}: '${value}',`)
      .join('\n')
    return `  ${mode}: {\n${colors}\n  },`
  })

  return `/** Generated by apps/mobile/scripts/generate-widget-colors.ts. Do not edit. */\n` +
    `export const widgetColorPalette = {\n${modes.join('\n')}\n} as const\n`
}

export async function generateWidgetColors() {
  const outputs: [string, string][] = [
    [path.join(mobileDirectory, 'lib/widget-colors.generated.ts'), generatedTypeScript()],
  ]

  for (const [outputPath, contents] of outputs) {
    await mkdir(path.dirname(outputPath), { recursive: true })
    await writeFile(outputPath, contents)
  }
}

/**
 * WHY: no package above this file declares `"type": "module"`, so tsx transforms it to CommonJS and
 * esbuild refuses a top-level await outright. Handling the promise keeps the command runnable while
 * still failing loudly and nonzero, which `void` alone leaves to a default flag.
 */
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  generateWidgetColors().catch((error: unknown) => {
    process.exitCode = 1
    throw error
  })
}
